import type { CardInput, Doc, RichNode } from '../shared/model';
const p = (text: string): RichNode => ({ type: 'paragraph', content: [{ type: 'text', text }] });
const m = (latex: string): RichNode => ({ type: 'blockMath', attrs: { latex } });
const doc = (...content: RichNode[]): Doc => ({ type: 'doc', content });
function card(
  title: string,
  type: CardInput['type'],
  ...back: RichNode[]
): Omit<CardInput, 'deckId'> {
  return { title, type, front: doc(p(title)), back: doc(...back), tags: ['Примеры'] };
}
